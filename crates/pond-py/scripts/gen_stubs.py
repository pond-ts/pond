"""Write the study methods into pond_rs.pyi from the catalog.

    python scripts/gen_stubs.py          # rewrite the block
    python scripts/gen_stubs.py --check  # exit 1 when it is out of date

Each study is a method on TimeSeries and PartitionedSeries (found at run
time by attribute lookup); this gives them type hints and docs. The block
sits between the two `# --- studies` marker lines in `class _Shared`.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import pond_rs

STUB = Path(__file__).resolve().parents[1] / "pond_rs.pyi"
BEGIN = "    # --- studies: generated by scripts/gen_stubs.py from pond_rs.studies() ---\n"
END = "    # --- end studies ---\n"


def snake(name: str) -> str:
    return re.sub(r"([A-Z])", lambda m: "_" + m.group(1).lower(), name)


def number(v) -> str:
    return repr(int(v)) if float(v).is_integer() else repr(float(v))


def param(name: str, p: dict) -> str:
    kind = p["kind"]
    if kind == "enum":
        t = "Literal[" + ", ".join(repr(o) for o in p["of"]) + "]"
        default = p.get("default")
        default = repr(default) if default is not None else None
    else:
        t = "int" if kind == "integer" else "float"
        default = number(p["default"]) if "default" in p else None
    if p.get("optional"):
        return f"{snake(name)}: Optional[{t}] = None"
    if default is None:
        return f"{snake(name)}: {t}"
    return f"{snake(name)}: {t} = {default}"


def describe_param(name: str, p: dict) -> str:
    bits = []
    if p["kind"] == "enum":
        bits.append("one of " + ", ".join(p["of"]))
    else:
        if "min" in p:
            bits.append(f"min {number(p['min'])}")
        if "max" in p:
            bits.append(f"max {number(p['max'])}")
        if "suggest" in p:
            lo, hi = p["suggest"]
            bits.append(f"usually {number(lo)}-{number(hi)}")
    if p.get("optional"):
        bits.append("leave out to switch off")
    elif "default" not in p:
        bits.append(f"required, e.g. {p.get('example')}")
    if "requires" in p:
        bits.append(f"needs {snake(p['requires'])}")
    return f"{snake(name)}: " + "; ".join(bits) if bits else snake(name)


def method(d: dict) -> str:
    args = []
    for i in d["inputs"]:
        if "default" in i:
            args.append(f"{snake(i['role'])}: str = {i['default']!r}")
        else:
            args.append(f"{snake(i['role'])}: str")
    required = [param(n, p) for n, p in d["params"].items() if " = " not in param(n, p)]
    optional = [param(n, p) for n, p in d["params"].items() if " = " in param(n, p)]
    naming = d["naming"]
    names = [*args, *required, *optional, f"{naming['kind']}: str = {naming['default']!r}"]
    if d.get("anchor") == "session":
        names += [
            "sessions: Union[TradingCalendar, Iterable[Session], None] = None",
            "session: Optional[str] = None",
            "stamped: Literal['open', 'close'] = 'open'",
        ]
    elif d.get("anchor") == "time":
        names.append("anchor: Time")
    # Every option is a keyword; required ones have no default.
    lines = [f"    def {d['method']}(", "        self,", "        *,"]
    lines += [f"        {n}," for n in names]
    lines.append("    ) -> Self:")
    doc = [d["summary"].rstrip(".") + "."]
    outs = ", ".join(d["output_names"])
    doc.append(f"Adds {outs} ({d['family']}).")
    notes = [describe_param(n, p) for n, p in d["params"].items()]
    if d.get("anchor") == "session":
        notes.append("give sessions= (a calendar or list) or session= (a session-id column)")
    if notes:
        doc.append("Options: " + "; ".join(notes) + ".")
    text = "\n".join(doc)
    lines.append('        """' + text.replace("\n", "\n        ") + '"""')
    return "\n".join(lines) + "\n"


def block() -> str:
    return "".join(method(d) for d in pond_rs.studies())


def main() -> int:
    stub = STUB.read_text()
    a = stub.index(BEGIN) + len(BEGIN)
    b = stub.index(END)
    new = stub[:a] + block() + stub[b:]
    if "--check" in sys.argv:
        if new != stub:
            print("pond_rs.pyi study methods are out of date: run python scripts/gen_stubs.py")
            return 1
        return 0
    STUB.write_text(new)
    return 0


if __name__ == "__main__":
    sys.exit(main())
