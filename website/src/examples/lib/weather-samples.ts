/**
 * **Real, measured data** — three US-government sources, all public domain.
 * The Gallery's weather & climate track (`gallery-c*.tsx`) draws all four
 * of its charts from this one module.
 *
 * ## 1. Seattle-Tacoma Intl (SEA), calendar 2024 — daily
 *
 * Daily maximum / minimum temperature (°C) and precipitation (mm) for GHCN
 * station `USW00024233`, from **NOAA NCEI's GHCN-Daily** `daily-summaries`
 * service (https://www.ncei.noaa.gov/access/services/data/v1), retrieved
 * 2026-08-04. Public domain (a work of the US government).
 *
 * One value per calendar day, so the **index is the day offset** from
 * `SEA_DAY0_MS` — no parallel time array to keep in step. Kept: TMAX, TMIN,
 * PRCP. Dropped: SNOW / SNWD (near-zero at sea level here) and the
 * observation flags, which say how a value was measured rather than what it
 * was.
 *
 * The `null`s are the station's own reporting gaps and stay in rather than
 * being interpolated: **TMIN** is missing 2024-04-25 and **PRCP**
 * 2024-04-24 and 2024-04-25 (TMAX is complete). They are why the
 * temperature band has a one-day hole in it and why the cumulative-rainfall
 * line holds flat across two days — missing data is a thing pond
 * represents, and a docs fixture shouldn't pretend otherwise.
 *
 * The 203 days of `0` in the precipitation channel are equally real: this
 * is a dry-summer climate, and of the 818.0 mm that fell in 2024, the
 * wettest single day (2024-02-28) took 24.1 mm of it.
 *
 * ## 2. The same station, 2024 — hourly wind
 *
 * Hourly METAR (`FM-15`) reports from **NOAA NCEI's Local Climatological
 * Data** service for WBAN `72793024233` — the same airport — retrieved
 * 2026-08-04, also public domain. 8,735 observations, in two forms:
 *
 * **`SEA_WIND_CODES`** is the observations themselves, one small integer
 * each, in report order: `0`–`15` for the compass sector clockwise from
 * north, `16` for calm, `17` for variable. Timestamps are not a parallel
 * array — the station reports at **:53 past the hour**, so a timestamp is
 * `SEA_WIND_T0_MS` plus 60 minutes per step, and the 28 places where that
 * cadence breaks (50 hours the station skipped, plus 1 off-cycle report)
 * are listed explicitly in `SEA_WIND_OFF_GRID`. Those 28 pairs are a few
 * hundred bytes where a delta per observation would have been tens of
 * kilobytes, and they put the irregularity in the fixture rather than
 * burying it in 8,735 mostly-identical numbers.
 *
 * The stamps are LCD's own *local standard time*, read as UTC — the same
 * convention as the daily series above. That is what makes a calendar-month
 * slice of the hourly series hold exactly the observations the monthly
 * matrix bins into that month, which the generator asserts rather than
 * assumes.
 *
 * **`SEA_WIND_HOURS`** is the same observations **binned into 16 compass
 * sectors × 12 months**, kept because four of the Gallery's numbers are
 * annual and monthly shares and recomputing them from 8,735 rows to draw 16
 * bars would be silly. The generator re-bins the emitted codes and checks
 * the two agree cell for cell, so they cannot drift apart.
 *
 * Two categories have no direction to bin and are kept separately rather
 * than folded into a sector: **calm** (621 hours, reported as direction 000
 * with zero speed) and **variable** (315 hours of `VRB` — a direction
 * shifting faster than the observation resolves). That leaves 7,799
 * directed hours in the sector matrix.
 *
 * ## 3. Global annual temperature anomaly, 1880–2025
 *
 * **NASA GISS Surface Temperature Analysis (GISTEMP v4)**, land-ocean
 * index, annual means (the `J-D` column of `GLB.Ts+dSST.csv`), retrieved
 * 2026-08-04. Public domain (NASA). Values are °C relative to the 1951–1980
 * mean — the series behind the "warming stripes". Only complete years are
 * kept, so the current partial year is absent; GISTEMP revises history as
 * station records are homogenised, which is what the retrieval date is for.
 *
 * Generated once by `website/scripts/fixtures/weather.mjs`, then committed.
 */

